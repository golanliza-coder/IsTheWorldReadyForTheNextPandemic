print(f"-> Full Epidemiology Shape: {df_epi.shape}")
print(f"-> Full Demographics Shape: {df_demo.shape}\n")


# ==========================================
# 2. STEP 1: TIME-SERIES DAILY MERGE
# ==========================================
print("Performing master baseline merge...")
# Standard left join maps static population traits to every matching location row
df_daily_master = pd.merge(
    df_epi,
    df_demo,
    on='location_key',
    how='left'
)

# Feature Engineering: Extract the Year from the string date field
df_daily_master['date'] = pd.to_datetime(df_daily_master['date'])
df_daily_master['Year'] = df_daily_master['date'].dt.year


# ==========================================
# 3. STEP 2: COUNTRY & ANNUAL AGGREGATION
# ==========================================
print("Creating Country-Year aggregate profile...")
# Grouping the full timeline data to get annual sums per country space
df_annual_analysis = df_daily_master.groupby(['location_key', 'Year']).agg({
    'new_confirmed': 'sum',
    'new_deceased': 'sum',
    'population': 'first',                 # Population is static per country
    'population_age_80_and_older': 'first' # Senior metric is static per country
}).reset_index()

# Rename columns to accurately represent annual aggregated data
df_annual_analysis = df_annual_analysis.rename(columns={
    'new_confirmed': 'annual_confirmed',
    'new_deceased': 'annual_deceased'
})


# ==========================================
# 4. STEP 3: VULNERABILITY METRIC CALCULATION
# ==========================================
# Safety check to avoid division-by-zero errors on empty population fields
df_annual_analysis = df_annual_analysis[df_annual_analysis['population'] > 0].copy()

# Compute the normalized 'Deceased Rate Per Capita'
df_annual_analysis['deceased_rate_per_capita'] = (
    df_annual_analysis['annual_deceased'] / df_annual_analysis['population']
)

# Compute normalized senior ratio for better statistical comparison
df_annual_analysis['senior_ratio_per_capita'] = (
    df_annual_analysis['population_age_80_and_older'] / df_annual_analysis['population']
)

print("Processing complete!")
print(f"-> Daily Timeline Rows: {df_daily_master.shape[0]}")
print(f"-> Aggregated Country-Year Rows: {df_annual_analysis.shape[0]}\n")


