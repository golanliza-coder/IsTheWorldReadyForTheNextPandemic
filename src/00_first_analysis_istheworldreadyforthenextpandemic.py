# 6. DESCRIPTIVE STATISTICS FOR MERGED TABLE
# ==========================================
print("\n" + "=" * 60)
print("     DESCRIPTIVE STATISTICS FOR AGGREGATED METRICS")
print("=" * 60)

# Choose the core metrics to analyze from your new table
target_metrics = ['annual_confirmed', 'annual_deceased', 'deceased_rate_per_capita']

# 1. Run the standard describe function for core metrics
# We transpose (.T) the result so metrics are columns and features are rows (cleaner layout)
base_stats = df_annual_analysis[target_metrics].describe().T

# 2. Add the specialized assignment metrics that describe() doesn't include
from scipy import stats
import numpy as np

geom_means = []
trimmed_means = []
modes = []

for col in target_metrics:
    clean_series = df_annual_analysis[col].dropna()

    # Calculate Mode (שכיח)
    modes.append(clean_series.mode()[0] if not clean_series.empty else np.nan)

    # Calculate Geometric Mean (Only for positive non-zero numbers)
    pos_data = clean_series[clean_series > 0]
    geom_means.append(stats.gmean(pos_data) if not pos_data.empty else np.nan)

    # Calculate Trimmed Mean (10% trimmed: 5% off each tail)
    trimmed_means.append(stats.trim_mean(clean_series, 0.05))

# Append the custom series directly into our summary table
base_stats['mode'] = modes
base_stats['geometric_mean'] = geom_means
base_stats['trimmed_mean_10%'] = trimmed_means

# 3. Clean and format the final statistical printout to 2 or 3 decimal places
pd.set_option('display.float_format', lambda x: f'{x:.3f}')
print(base_stats[['count', 'mean', '50%', 'mode', 'geometric_mean', 'trimmed_mean_10%', 'min', 'max']])
print("=" * 60)

# 4. Distribution Analysis Note Example for Deceased Rate Per Capita
mean_dr = base_stats.loc['deceased_rate_per_capita', 'mean']
median_dr = base_stats.loc['deceased_rate_per_capita', '50%']

print("\n💡 Distribution Insights (deceased_rate_per_capita):")
if mean_dr > median_dr:
    print(f"   Mean ({mean_dr:.3f}) > Median ({median_dr:.3f}) → Right-skewed distribution!")
else:
    print(f"   Mean ({mean_dr:.3f}) <= Median ({median_dr:.3f}) → Symmetrical or Left-skewed distribution!")